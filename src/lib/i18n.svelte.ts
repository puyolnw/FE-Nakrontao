export type Key = keyof (typeof dict)['th'];

const stored = typeof localStorage !== 'undefined' ? safeGet() : null;
function safeGet(): Lang | null {
	try {
		const v = localStorage.getItem('lang');
		return v === 'th' || v === 'zh' || v === 'en' ? v : null;
	} catch {
		return null;
	}
}
function initial(): Lang {
	if (stored) return stored;
	const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'th';
	if (nav.startsWith('zh')) return 'zh';
	if (nav.startsWith('th')) return 'th';
	return nav.startsWith('en') ? 'en' : 'th';
}

export const i18n = $state({ lang: initial() });

export function setLang(l: Lang) {
	i18n.lang = l;
	document.documentElement.lang = l === 'zh' ? 'zh-Hans' : l;
	try {
		localStorage.setItem('lang', l);
	} catch {
		/* private mode: language just won't persist */
	}
}

export function t(key: Key): string {
	return dict[i18n.lang][key] ?? dict.th[key];
}

// Demo/seed content is tagged "(ตัวอย่าง)", "[Sample]", "【示例】"… so researchers can spot it in the
// admin. Visitors should not read those tags in every title: strip them here and show a small
// badge instead (see isSample).
const SAMPLE = /\s*(?:\((?:ตัวอย่าง|sample|示例)\)|\[(?:ตัวอย่าง|sample|示例)\]|【示例】|（示例）|\[ข้อความตัวอย่าง[^\]]*\])\s*/giu;

/** Pick the current language from a translated field, falling back to Thai. */
export function tr(v: I18n | null | undefined): string {
	if (!v) return '';
	return (v[i18n.lang] || v.th || v.zh || v.en || '').replace(SAMPLE, ' ').trim();
}

/** True when a translated field carries a sample/demo tag in any language. */
export function isSample(...vs: (I18n | null | undefined)[]): boolean {
	return vs.some((v) => !!v && Object.values(v).some((s) => typeof s === 'string' && new RegExp(SAMPLE.source, 'iu').test(s)));
}

export function reason(code: string): string {
	const [k, detail] = code.split(':');
	const label = tx(`reason.${k}`);
	if (k === 'match_category' && detail) return `${label} · ${tx(`cat.${detail}`)}`;
	if (k === 'match_tag' && detail) return `${label} · ${detail.replace(/_/g, ' ')}`;
	return label;
}

const locales: Record<Lang, string> = { th: 'th-TH', zh: 'zh-CN', en: 'en-GB' };

export function fmtDate(iso: string, opts: Intl.DateTimeFormatOptions = { dateStyle: 'long' }): string {
	return new Intl.DateTimeFormat(locales[i18n.lang], opts).format(new Date(iso));
}

export function fmtTime(iso: string): string {
	return new Intl.DateTimeFormat(locales[i18n.lang], { hour: '2-digit', minute: '2-digit' }).format(new Date(iso));
}

/** For keys built at runtime (e.g. `kind.${k.kind}`); falls back to the raw key when unknown. */
export function tx(key: string): string {
	return (dict[i18n.lang] as Record<string, string>)[key] ?? (dict.th as Record<string, string>)[key] ?? key;
}
